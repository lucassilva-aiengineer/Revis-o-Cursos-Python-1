# Bibliotecas 

# As bibliotecas são arquivos de código ou pastas de arquivos de códigos que podem ser acessadas por meio de importação ou download e 
# importação. As bibliotecas, também conhecidas como libs, existem para evitarem a necessidade de sempre se ter que instalar junto a linguagem python todas 
# as bibliotecas, funções e classes possíveis e imagináveis já criadas, economizando memória por meio de uma atuação modular, em partes, se instala apenas os módulos 
# que serão utilizados. Além disto, esta abordagem modular impede os chamados conflitos, situações onde existêm ambiguidades, mesmos nomes para definições diferentes
# da linguagem. 


